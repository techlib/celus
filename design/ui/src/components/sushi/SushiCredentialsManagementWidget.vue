      this.loadSushiCredentialsCount();
    },
    createSearchFilter() {
      let words = [];
      if (this.search) {
        words = this.search.toLowerCase().split(/ /);
      }
      function filter(item) {
        for (let word of words) {
          let match = false;
          if (item.title.toLowerCase().indexOf(word) >= 0) match = true;
          if (item.organization.short_name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (item.organization.name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (item.platform.name.toLowerCase().indexOf(word) >= 0) match = true;
          if (item.platform.short_name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (!match) {
            // no match for this word
            return false;
          }
        }
        return true;
      }
      return filter;
    },
    extractLastHarvestableMonth(counter_reports) {
      let count = 0;
      let month = null;
      for (const crt of counter_reports) {
        if (crt.last_harvestable_month) {
          month =
            month !== null && month < crt.last_harvestable_month
              ? month
              : crt.last_harvestable_month;
          count += 1;
        }
      }
      return [
        {
          fake_id: "fake_id",
          month: month ? month.slice(0, 7) : null,
          count: count > 1 ? `+${count - 1}` : null,
        },
      ];
    },
    warnSameCredentials(creds) {
      if (this.consortialInstall) {
        return creds.same_global > 1;
      } else {
        return creds.same_in_org > 1;
      }
    },
    warnSameCredentialsText(creds) {
      if (creds.same_in_org > 1) {
        return "warn_same_credentials_in_org_tooltip";
      }
      if (creds.same_global > 1) {
        return "warn_same_credentials_global_tooltip";
      }
      return "";
    },
