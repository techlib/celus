import { mapActions, mapGetters } from "vuex";
import debounce from "lodash/debounce";
import CheckMark from "@/components/util/CheckMark";
import CounterReportLastHarvestableMonthWidget from "@/components/sushi/CounterReportLastHarvestableMonthWidget";
import SushiAttemptListWidget from "@/components/sushi/SushiAttemptListWidget";
import SushiCredentialsDataDialog from "@/components/sushi/SushiCredentialsDataDialog";
import SushiCredentialsEditDialog from "@/components/sushi/SushiCredentialsEditDialog";
import SushiReportIndicator from "@/components/sushi/SushiReportIndicator";
import HarvestSelectedWidget from "@/components/sushi/HarvestSelectedWidget";
import stateTracking from "@/mixins/stateTracking";
import PlatformSelector from "@/components/selectors/PlatformSelector.vue";

export default {
  name: "SushiCredentialsManagementWidget",

  components: {
    CheckMark,
    HarvestSelectedWidget,
    PlatformSelector,
    CounterReportLastHarvestableMonthWidget,
    SushiAttemptListWidget,
    SushiCredentialsEditDialog,
    SushiCredentialsDataDialog,
    SushiReportIndicator,
  },
  mixins: [stateTracking],

  props: {
    dialogMaxWidth: {
      required: false,
      default: "1200px",
    },
    organizationId: {
      default: -1,
      type: Number,
      required: false,
    },
    platformId: {
      default: null,
      type: Number,
      required: false,
    },
    showProblematicOnly: {
      default: false,
      type: Boolean,
    },
    showPlatformFilter: {
      default: false,
      type: Boolean,
    },
  },

  data() {
    return {
      sushiCredentialsList: [],
      search: "",
      selectedCredentials: null,
      showEditDialog: false,
      showDetailsDialog: false,
      showCreateDialog: false,
      showDataDialog: false,
      showLastHarvestableMonthDialog: false,
      loading: false,
      counterVersion: null,
      withLastHarvestableMonthSet: null,
      checkedRows: [],
      showTestDialog: false,
      problematicOnly: this.showProblematicOnly,
      exportAllCredentialsUrl:
        "/api/sushi-credentials/export-all-credentials/?export_all=true",
      platformFilter: null,
      // table options
      page: 1,
      itemsPerPage: 25,
      orderBy: ["organization.name", "platform.name", "counter_version"],
      orderDesc: [false, false, false],
      // state tracking support
      watchedAttrs: [
        {
          name: "problematicOnly",
          type: Boolean,
        },
        {
          name: "search",
          type: String,
        },
        {
          name: "counterVersion",
          type: Number,
        },
        {
          name: "withLastHarvestableMonthSet",
          type: Boolean,
        },
        {
          name: "page",
          type: Number,
        },
        {
          name: "itemsPerPage",
          type: Number,
          var: "ipp",
        },
        {
          name: "orderBy",
          type: Array,
          alwaysTrack: true,
        },
        {
          name: "orderDesc",
          type: Array,
        },
        {
          name: "platformFilter",
          type: Number,
        },
      ],
    };
  },
  computed: {
    ...mapGetters({
      consortialInstall: "consortialInstall",
      contactEmail: "contactEmail",
      subjectForImportCredEmail: "subjectForImportCredEmail",
      selectedOrganization: "selectedOrganization",
    }),
    getCSRFToken() {
      let csrftoken = Cookies.get("csrftoken");
      return csrftoken;
    },
    headers() {
      const large = this.$vuetify.breakpoint.lgAndUp;
      let allHeaders = [
        {
          text: this.$i18n.t("title"),
          value: "title",
          class: "wrap",
        },
        {
          text: this.$i18n.t("organization"),
          value: "organization.name",
          class: "wrap",
        },
        {
          text: this.$i18n.t("platform"),
          value: "platform.name",
        },
        {
          text: this.$i18n.t("title_fields.counter_version"),
          value: "counter_version",
          align: "end",
        },
        {
          text: this.$i18n.t("title_fields.active_reports"),
          value: "counter_reports",
          sortable: false,
        },
        {
          text: this.$i18n.t("title_fields.last_harvestable_month"),
          value: "last_harvestable_month",
          sortable: false,
        },
        {
          text: this.$i18n.t("title_fields.outside_consortium"),
          value: "outside_consortium",
          show: this.consortialInstall && large,
        },
        {
          text: this.$i18n.t("sushi.enabled"),
          value: "enabled",
        },
        {
          text: this.$i18n.t("title_fields.lock"),
          value: "locked",
          show: this.consortialInstall && large,
        },
        {
          text: this.$i18n.t("title_fields.actions"),
          value: "actions",
          sortable: false,
        },
      ];
      return allHeaders.filter(
        (row) => !row.hasOwnProperty("show") || row.show
      );
    },
    searchDebounced: {
      get() {
        return this.search;
      },
      set: debounce(function (value) {
        this.search = value;
      }, 500),
    },
    dataUrl() {
      let base = `/api/sushi-credentials/?organization=${this.organizationId}`;
      if (this.platformId) {
        base += `&platform=${this.platformId}`;
      }
      return base;
    },
    filteredCredentials() {
      return this.sushiCredentialsList
        .filter((item) =>
          this.problematicOnly
            ? !item.verified || item.broken || item.has_broken_reports
            : true
        )
        .filter(
          (item) =>
            this.counterVersion === null ||
            this.counterVersion === item.counter_version
        )
        .filter(
          (item) =>
            this.withLastHarvestableMonthSet === null ||
            this.withLastHarvestableMonthSet ===
              item.counter_reports_long.some(
                (e) => e.last_harvestable_month != null
              )
        )
        .filter(this.createSearchFilter())
        .filter((item) =>
          this.platformFilter ? item.platform.pk === this.platformFilter : true
        );
    },
    checkedCredentials() {
      let filteredIds = new Set(
        this.filteredCredentials.map((item) => item.pk)
      );
      return this.checkedRows.filter((item) => filteredIds.has(item.pk));
    },
    exportUrl() {
      let base = `/api/sushi-credentials/export-credentials/?organization=${this.organizationId}`;
      if (this.platformId) {
        base += `&platform=${this.platformId}`;
      }
      return base;
    },
    exportForImportUrl() {
      let base = `/api/sushi-credentials/import-template/?organization=${this.organizationId}`;
      if (this.platformId) {
        base += `&platform=${this.platformId}`;
      }
      return base;
    },
    platforms() {
      let platforms = new Set();
      let ret = [];
      this.sushiCredentialsList.forEach((item) => {
        if (!platforms.has(item.platform.pk)) {
          platforms.add(item.platform.pk);
          ret.push(item.platform);
        }
      });
      return ret.sort((a, b) => a.name.localeCompare(b.name));
    },
  },

  methods: {
    ...mapActions({
      showSnackbar: "showSnackbar",
      loadSushiCredentialsCount: "loadSushiCredentialsCount",
      getPageSetting: "getPageSetting",
      setPageSetting: "setPageSetting",
    }),
    downloadImportTemplate() {
      const link = document.createElement("a");
      link.href = this.exportForImportUrl;
      document.body.appendChild(link);
      link.click();
    },
    async showImportCredentialsModal() {
      const res = await this.$confirm(
        this.$t("import_credentials_confirm_text_1") +
          "<br><br>" +
          this.$t("import_credentials_confirm_text_2") +
          ` <a href="mailto:${this.contactEmail}?subject=${this.subjectForImportCredEmail}">${this.contactEmail}</a> ` +
          this.$t("import_credentials_confirm_text_3") +
          ` "${this.subjectForImportCredEmail}". ` +
          this.$t("import_credentials_confirm_text_4"),
        {
          title: this.$t("import_credentials_confirm_title"),
          buttonTrueText: this.$t("download_file"),
          buttonFalseText: this.$t("close"),
          color: "primary",
          icon: "fa fa-info-circle",
          width: 500,
        }
      );
      if (res) {
        this.downloadImportTemplate();
      }
    },
    showFilterCredentials() {
      if (this.filteredCredentials.length === 0) {
        this.$confirm(this.$t("filter_at_least_one_credentials"), {
          title: this.$t("no_credentials_filtered"),
          buttonTrueText: this.$t("close"),
          buttonFalseText: null,
        });
      }
    },
    showSelectCredentials() {
      if (this.checkedCredentials.length === 0) {
        this.$confirm(this.$t("select_at_least_one_credentials"), {
          title: this.$t("no_credentials_selected"),
          buttonTrueText: this.$t("close"),
          buttonFalseText: null,
        });
      }
    },
    showAddCredentials() {
      if (this.sushiCredentialsList.length === 0) {
        this.$confirm(this.$t("first_add_some_credentials"), {
          title: this.$t("there_are_no_credentials"),
          buttonTrueText: this.$t("close"),
          buttonFalseText: null,
        });
      }
    },
    async loadSushiCredentialsList() {
      this.loading = true;
      try {
        let response = await axios.get(this.dataUrl);
        this.sushiCredentialsList = response.data;
        this.sushiCredentialsList.forEach((item) =>
          this.preprocessCredentials(item)
        );
      } catch (error) {
        this.showSnackbar({
          content: "Error loading credentials list: " + error,
        });
      } finally {
        this.loading = false;
      }
    },
    async reloadSelectedCredentials() {
      if (this.selectedCredentials) {
        try {
          let response = await axios.get(
            `/api/sushi-credentials/${this.selectedCredentials.pk}/`
          );
          this.updateCredentials(response.data);
        } catch (error) {
          this.showSnackbar({
            content: "Could not reload credentials: " + error,
            color: "error",
          });
        }
      }
    },
    updateCredentials(credentials) {
      this.preprocessCredentials(credentials);
      // the new credentials as returned by the edit dialog
      // we put them at the right place in the list of credentials
      let found = false;
      for (let i = 0; i < this.sushiCredentialsList.length; i++) {
        if (this.sushiCredentialsList[i].pk === credentials.pk) {
          this.$set(this.sushiCredentialsList, i, credentials);
          found = true;
          break;
        }
      }
      // checkedRows contains a copy of the credentials, so we need to update it as well
      for (let i = 0; i < this.checkedRows.length; i++) {
        if (this.checkedRows[i].pk === credentials.pk) {
          this.$set(this.checkedRows, i, credentials);
          break;
        }
      }
      if (!found) {
        // we did not find the corresponding record - we add it at the end
        this.sushiCredentialsList.push(credentials);
      }
      // update the model used by the edit dialog
      if (this.selectedCredentials) {
        this.selectedCredentials = credentials;
      }
    },
    deleteCredentials({ id }) {
      this.sushiCredentialsList = this.sushiCredentialsList.filter(
        (item) => item.pk !== id
      );
    },
    preprocessCredentials(item) {
      item["has_broken_reports"] = !!item.counter_reports_long.filter(
        (report) => report.broken
      ).length;
      //tem["isSelectable"] = !item.broken;
      if (item.broken) {
        // we need to make sure a broken item is not checked
        this.checkedRows = this.checkedRows.filter((row) => row.pk !== item.pk);
      }
      if (!item.platform.name) {
        // use platform short_name instead of name if name is empty
        item.platform.name = item.platform.short_name;
      }
    },
    async toggleLock(credentials) {
      let newLockLevel = 400;
      if (credentials.locked) {
        newLockLevel = 300;
      }
      try {
        let response = await axios.post(
          `/api/sushi-credentials/${credentials.pk}/lock/`,
          { lock_level: newLockLevel }
        );
        credentials.lock_level = response.data.lock_level;
        credentials.locked = response.data.locked;
      } catch (error) {
        this.showSnackbar({
          content: "Error (un)locking credentials: " + error,
          color: "error",
        });
      }
    },
    closeDetailsDialog() {
      this.selectedCredentials = null;
      this.showDetailsDialog = false;
    },
    closeDataDialog() {
      this.selectedCredentials = null;
      this.showDataDialog = false;
    },
    closeLastHarvestableMonthDialog(refresh) {
      if (refresh) {
        this.loadSushiCredentialsList();
        this.checkedRows = [];
      }
      this.showLastHarvestableMonthDialog = false;
    },
    activateCreateDialog() {
      this.showCreateDialog = true;
    },
    testChecked(dialogFlag) {
      if (this.checkedCredentials.length > 0) {
        this[dialogFlag] = true;
      } else {
        this.$confirm(this.$t("select_at_least_one_credentials"), {
          title: this.$t("no_credentials_selected"),
          buttonTrueText: this.$t("close"),
          buttonFalseText: null,
        });
      }
    },
    stopTestDialog() {
      if (this.$refs.testWidget) {
        this.$refs.testWidget.clean();
      }
      this.showTestDialog = false;
      this.loadSushiCredentialsList();
      this.loadSushiCredentialsCount();
    },
    createSearchFilter() {
      let words = [];
      if (this.search) {
        words = this.search.toLowerCase().split(/ /);
      }
      function filter(item) {
        for (let word of words) {
          let match = false;
          if (item.title.toLowerCase().indexOf(word) >= 0) match = true;
          if (item.organization.short_name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (item.organization.name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (item.platform.name.toLowerCase().indexOf(word) >= 0) match = true;
          if (item.platform.short_name.toLowerCase().indexOf(word) >= 0)
            match = true;
          if (!match) {
            // no match for this word
            return false;
          }
        }
        return true;
      }
      return filter;
    },
    extractLastHarvestableMonth(counter_reports) {
      let count = 0;
      let month = null;
      for (const crt of counter_reports) {
        if (crt.last_harvestable_month) {
          month =
            month !== null && month < crt.last_harvestable_month
              ? month
              : crt.last_harvestable_month;
          count += 1;
        }
      }
      return [
        {
          fake_id: "fake_id",
          month: month ? month.slice(0, 7) : null,
          count: count > 1 ? `+${count - 1}` : null,
        },
      ];
    },
  },

  watch: {
    showEditDialog(value) {
      if (!value) {
        this.selectedCredentials = null;
        this.loadSushiCredentialsCount();
      }
    },
    showCreateDialog(value) {
      if (!value) {
        this.selectedCredentials = null;
        this.loadSushiCredentialsCount();
      }
    },
    dataUrl() {
      this.loadSushiCredentialsList();
    },
    itemsPerPage() {
      this.setPageSetting({
        page: this.$route.name,
        key: "itemsPerPage",
        value: this.itemsPerPage,
      });
    },
  },
  async mounted() {
    const ippSetting = await this.getPageSetting({
      page: this.$route.name,
      key: "itemsPerPage",
    });
    if (ippSetting) {
      this.itemsPerPage = ippSetting;
    }
    await this.loadSushiCredentialsList();
  },
};
</script>

